import { dev } from '$app/environment';
import { json, type Handle } from '@sveltejs/kit';
import { clearSessionCookie } from '$lib/server/auth/cookie';
import { SESSION_COOKIE, getSessionUser } from '$lib/server/auth/session';
import { isForbiddenApiMutation } from '$lib/server/csrf';
import { getDb } from '$lib/server/db';
import { recordAppOpen, shouldRecordAppOpen } from '$lib/server/events';
import { isPublicPath } from '$lib/server/publicPaths';

function unauthenticated(pathname: string, isDataRequest: boolean): Response {
	if (pathname === '/api' || pathname.startsWith('/api/') || pathname.startsWith('/media/')) {
		return json({ error: 'unauthorized' }, { status: 401 });
	}
	if (isDataRequest) {
		// A bare 303 would be followed by fetch and the client would try to parse the login HTML as
		// JSON; this is the shape SvelteKit itself uses for load-time redirects.
		return json({ type: 'redirect', status: 303, location: '/login' });
	}
	return new Response(null, { status: 303, headers: { Location: '/login' } });
}

export const handle: Handle = async ({ event, resolve }) => {
	if (isForbiddenApiMutation(event.request, event.url)) {
		return new Response('Cross-origin request blocked', { status: 403 });
	}

	event.locals.user = null;
	const sessionId = event.cookies.get(SESSION_COOKIE);
	if (sessionId) {
		event.locals.user = await getSessionUser(getDb(), sessionId);
		if (!event.locals.user) clearSessionCookie(event.cookies);
	}

	if (event.locals.user && shouldRecordAppOpen(event.request, event.url)) {
		// Fire and forget: analytics must never slow down or fail a request.
		recordAppOpen(getDb(), event.locals.user.id).catch(() =>
			console.warn('Could not record app_open event')
		);
	}

	// Global guard: every path not on the public allow-list needs a session (deactivated users
	// resolve to no user above). Per-route checks stay as defense in depth.
	const blocked = !event.locals.user && !isPublicPath(event.url.pathname);
	const response = blocked ? unauthenticated(event.url.pathname, event.isDataRequest) : await resolve(event);
	// The CSP itself (with nonces) is generated by SvelteKit from kit.csp in svelte.config.js.
	response.headers.set('X-Content-Type-Options', 'nosniff');
	response.headers.set('X-Frame-Options', 'DENY');
	response.headers.set('Referrer-Policy', 'strict-origin-when-cross-origin');
	response.headers.set('Permissions-Policy', 'camera=(self), microphone=(), geolocation=()');
	if (!dev) {
		response.headers.set('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');
	}
	return response;
};
